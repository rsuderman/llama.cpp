def transient_access(kind):
    if kind == "input":
        return "GGML_BACKEND_HRX_LOOM_BUFFER_ACCESS_READ"
    if kind == "output":
        return "GGML_BACKEND_HRX_LOOM_BUFFER_ACCESS_WRITE"
    if kind == "inout":
        return "GGML_BACKEND_HRX_LOOM_BUFFER_ACCESS_READ_WRITE"
    raise ValueError(f"unsupported buffer kind {kind}")


def graph_transient_indices(dispatches, base_index=0):
    indices = {}
    next_index = base_index
    for dispatch in dispatches:
        for buffer in route_schema.require_array(dispatch, "buffers", "route"):
            if buffer.get("storage") != "graph_transient":
                continue
            tensor = route_schema.require_string(buffer, "tensor", "route")
            if tensor not in indices:
                indices[tensor] = next_index
                next_index += 1
    return indices


def emit_graph_transient_materialization(lines, graph_indices, route_constant):
    for tensor, transient_index in graph_indices.items():
        tensor_expr = route_emit.role_var(tensor)
        lines.extend([
            f"    plan->transients[{transient_index}].graph_tensor = {tensor_expr};",
            f"    plan->transients[{transient_index}].size = ggml_nbytes({tensor_expr});",
            f"    if (plan->transients[{transient_index}].size == 0) {{",
            f"        return ggml_backend_hrx_loom_failed({route_constant});",
            "    }",
        ])


def emit_graph_transient_binding(lines, dispatch_expr, position, kind, tensor, transient_index):
    tensor_expr = route_emit.role_var(tensor)
    access = transient_access(kind)
    lines.extend([
        f"    {dispatch_expr}.transient_binding_indices[{position}] = {transient_index};",
        f"    {dispatch_expr}.transient_binding_accesses[{position}] = {access};",
        f"    {dispatch_expr}.bindings[{position}].length = ggml_nbytes({tensor_expr});",
    ])


def emit_plan_materialization(lines, route, definition, context, consumed_node_indices=None):
    route_id = route_schema.require_string(route, "id", "route")
    route_constant = route_id_constant(route_id)
    dispatches = route_schema.require_list(route, "dispatches", "route")
    route_dispatch = dispatches[0]
    graph_indices = graph_transient_indices(dispatches)
    if len(graph_indices) > 4:
        raise ValueError("route has too many transient buffers")
    buffers = sorted(route_schema.require_array(route_dispatch, "buffers", "route"), key=lambda item: item["position"])
    scalars = sorted(route_schema.require_array(route_dispatch, "scalars", "route"), key=lambda item: item["position"])
    dispatch = route_schema.require_dict(route_dispatch, "dispatch", "route")
    abi = route_schema.require_dict(definition, "abi", "definition")
    constant_byte_length = route_schema.require_int(abi, "constant_byte_length", "definition")
    offsets, constants_size = scalar_offsets(scalars, "route")
    if constants_size != constant_byte_length:
        raise ValueError(f"route scalar size {constants_size} does not match definition constant bytes {constant_byte_length}")

    dispatch_expr = "plan->dispatches[0]"
    lines.extend([
        "    if (ggml_backend_hrx_loom_match_only(plan)) {",
        f"        return ggml_backend_hrx_loom_supported({route_constant});",
        "    }",
    ])
    lines.append(PLAN_SETUP_TEMPLATE.format(route_id_constant=route_constant))
    if consumed_node_indices is not None:
        if len(consumed_node_indices) > MAX_CONSUMED_NODES:
            raise ValueError(f"route consumes too many graph nodes: {len(consumed_node_indices)}")
        lines.append(f"    plan->consumed_node_count = {len(consumed_node_indices)};")
        for i, node_index in enumerate(consumed_node_indices):
            lines.append(f"    plan->consumed_node_indices[{i}] = {node_index};")
    lines.extend([
        "    if (ggml_backend_hrx_loom_reorder_match(request, plan)) {",
        f"        return ggml_backend_hrx_loom_supported({route_constant});",
        "    }",
        "    if (!request->stream || !request->bind_tensor) {",
        f"        return ggml_backend_hrx_loom_failed({route_constant});",
        "    }",
    ])
    emit_graph_transient_materialization(lines, graph_indices, route_constant)
    if graph_indices:
        lines.append(f"    plan->transient_count = {len(graph_indices)};")
    lines.extend([
        f"    {dispatch_expr}.entry = entry;",
        "    plan->dispatch_count = 1;",
    ])
    emit_config_materialization(lines, route_dispatch)
    emit_dispatch_config_plan_copy(lines, route_dispatch, dispatch_expr)

    for buffer in buffers:
        position = route_schema.require_int(buffer, "position", "route")
        tensor = route_schema.require_string(buffer, "tensor", "route")
        if buffer.get("storage") == "graph_transient":
            emit_graph_transient_binding(
                lines,
                dispatch_expr,
                position,
                route_schema.require_string(buffer, "kind", "route"),
                tensor,
                graph_indices[tensor],
            )
        else:
            lines.append(BIND_BUFFER_TEMPLATE.format(
                dispatch_expr=dispatch_expr,
                tensor=route_emit.role_var(tensor),
                position=position,
                route_id_constant=route_constant,
            ))
    lines.append(f"    {dispatch_expr}.binding_count = {len(buffers)};")

    for scalar, offset in zip(scalars, offsets):
        name = route_schema.require_string(scalar, "name", "route")
        scalar_type = route_schema.require_string(scalar, "type", "route")
        cpp_type = CPP_SCALAR_TYPES[scalar_type]
        if "source" in scalar:
            value = typed_expr(source_expr(route_schema.require_string(scalar, "source", "route")), scalar_type)
        else:
            value = scalar_literal(scalar["value"], scalar_type)
        temp = f"constant_{c_identifier(name)}"
        lines.append(PACK_SCALAR_TEMPLATE.format(
            cpp_type=cpp_type,
            name=temp,
            value=value,
            offset=offset,
        ).replace("plan->constants", f"{dispatch_expr}.constants"))
    lines.append(f"    {dispatch_expr}.constants_size = {constant_byte_length};")

    dispatch_lines = route_emit.emit_dispatch_config(dispatch, context, route_constant, failed_response, route_schema)
    lines.extend([
        line.replace("plan->dispatch", f"{dispatch_expr}.dispatch")
            .replace("entry->workgroup_size", f"{dispatch_expr}.entry->workgroup_size")
        for line in dispatch_lines
    ])

    lines.append(f"    return ggml_backend_hrx_loom_supported({route_constant});")


def emit_step_materialization(lines, route_id, dispatches, step_index, step, definition, context, transient_indices):
    route_constant = route_id_constant(route_id)
    entry_constant = route_entry_constant(route_id, dispatches, step_index)
    step_expr = f"plan->dispatches[{step_index}]"
    buffers = sorted(route_schema.require_array(step, "buffers", "route"), key=lambda item: item["position"])
    scalars = sorted(route_schema.require_array(step, "scalars", "route"), key=lambda item: item["position"])
    dispatch = route_schema.require_dict(step, "dispatch", "route")
    abi = route_schema.require_dict(definition, "abi", "definition")
    constant_byte_length = route_schema.require_int(abi, "constant_byte_length", "definition")
    offsets, constants_size = scalar_offsets(scalars, "route")
    if constants_size != constant_byte_length:
        raise ValueError(f"step scalar size {constants_size} does not match definition constant bytes {constant_byte_length}")

    lines.extend([
        f"    const ggml_backend_hrx_loom_catalog_entry * step_{step_index}_entry = ggml_backend_hrx_loom_find_entry(catalog, {entry_constant});",
        f"    if (!step_{step_index}_entry) {{",
        "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_TARGET);",
        "    }",
        f"    {step_expr}.entry = step_{step_index}_entry;",
    ])
    emit_step_config_plan_copy(lines, step, step_expr)

    for buffer in buffers:
        position = route_schema.require_int(buffer, "position", "route")
        if "tensor" in buffer:
            tensor = route_schema.require_string(buffer, "tensor", "route")
            if buffer.get("storage") == "graph_transient":
                emit_graph_transient_binding(
                    lines,
                    step_expr,
                    position,
                    route_schema.require_string(buffer, "kind", "route"),
                    tensor,
                    transient_indices[tensor],
                )
            else:
                lines.extend([
                    f"    {step_expr}.transient_binding_indices[{position}] = -1;",
                    f"    {step_expr}.transient_binding_accesses[{position}] = GGML_BACKEND_HRX_LOOM_BUFFER_ACCESS_NONE;",
                    f"    if (!ggml_backend_hrx_loom_bind_tensor(request, {route_emit.role_var(tensor)}, &{step_expr}.bindings[{position}])) {{",
                    f"        return ggml_backend_hrx_loom_failed({route_constant});",
                    "    }",
                ])
        else:
            transient = route_schema.require_string(buffer, "transient", "route")
            transient_index = transient_indices[transient]
            lines.extend([
                f"    {step_expr}.transient_binding_indices[{position}] = {transient_index};",
                f"    {step_expr}.transient_binding_accesses[{position}] = {transient_access(route_schema.require_string(buffer, 'kind', 'route'))};",
                f"    {step_expr}.bindings[{position}].offset = plan->transients[{transient_index}].offset;",
                f"    {step_expr}.bindings[{position}].length = plan->transients[{transient_index}].size;",
            ])
    lines.append(f"    {step_expr}.binding_count = {len(buffers)};")

    for scalar, offset in zip(scalars, offsets):
        name = route_schema.require_string(scalar, "name", "route")
        scalar_type = route_schema.require_string(scalar, "type", "route")
        cpp_type = CPP_SCALAR_TYPES[scalar_type]
        if "source" in scalar:
            value = typed_expr(source_expr(route_schema.require_string(scalar, "source", "route")), scalar_type)
        else:
            value = scalar_literal(scalar["value"], scalar_type)
        temp = f"step_{step_index}_constant_{c_identifier(name)}"
        lines.append(PACK_SCALAR_TEMPLATE.format(
            cpp_type=cpp_type,
            name=temp,
            value=value,
            offset=offset,
        ).replace("plan->constants", f"{step_expr}.constants"))
    lines.append(f"    {step_expr}.constants_size = {constant_byte_length};")

    dispatch_lines = route_emit.emit_dispatch_config(dispatch, context, route_constant, failed_response, route_schema)
    lines.append("    {")
    lines.extend([
        line.replace("plan->dispatch", f"{step_expr}.dispatch")
            .replace("entry->workgroup_size", f"{step_expr}.entry->workgroup_size")
        for line in dispatch_lines
    ])
    lines.append("    }")


def emit_multi_step_plan_materialization(lines, route, step_definitions, context, consumed_node_indices=None):
    route_id = route_schema.require_string(route, "id", "route")
    route_constant = route_id_constant(route_id)
    transient_buffers = route.get("transient_buffers", {})
    steps = route_schema.require_list(route, "dispatches", "route")
    if len(transient_buffers) > 4:
        raise ValueError("route has too many transient buffers")
    if len(steps) > 5:
        raise ValueError("route has too many dispatches")
    graph_indices = graph_transient_indices(steps, len(transient_buffers))
    if len(transient_buffers) + len(graph_indices) > 4:
        raise ValueError("route has too many transient buffers")

    lines.extend([
        "    if (ggml_backend_hrx_loom_match_only(plan)) {",
        f"        return ggml_backend_hrx_loom_supported({route_constant});",
        "    }",
    ])
    lines.append(MULTI_STEP_PLAN_SETUP_TEMPLATE.format(route_id_constant=route_constant))
    if consumed_node_indices is not None:
        if len(consumed_node_indices) > MAX_CONSUMED_NODES:
            raise ValueError(f"route consumes too many graph nodes: {len(consumed_node_indices)}")
        lines.append(f"    plan->consumed_node_count = {len(consumed_node_indices)};")
        for i, node_index in enumerate(consumed_node_indices):
            lines.append(f"    plan->consumed_node_indices[{i}] = {node_index};")
    lines.extend([
        "    if (ggml_backend_hrx_loom_reorder_match(request, plan)) {",
        f"        return ggml_backend_hrx_loom_supported({route_constant});",
        "    }",
        "    if (!request->stream || !request->bind_tensor) {",
        f"        return ggml_backend_hrx_loom_failed({route_constant});",
        "    }",
    ])

    transient_indices = {}
    lines.append("    size_t transient_cursor = 0;")
    for i, (name, transient) in enumerate(transient_buffers.items()):
        size_expr = emit_integer_operand(transient["size"], context)
        transient_indices[name] = i
        lines.extend([
            "    if (!ggml_backend_hrx_loom_align_size(transient_cursor, GGML_BACKEND_HRX_LOOM_TRANSIENT_ALIGNMENT, &transient_cursor)) {",
            "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_CONFIG);",
            "    }",
            f"    const int64_t transient_{i}_size_value = {size_expr};",
            f"    if (transient_{i}_size_value <= 0) {{",
            "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_CONFIG);",
            "    }",
            f"    const size_t transient_{i}_size = static_cast<size_t>(transient_{i}_size_value);",
            f"    plan->transients[{i}].offset = transient_cursor;",
            f"    plan->transients[{i}].size = transient_{i}_size;",
            f"    if (!ggml_backend_hrx_loom_checked_add_size(transient_cursor, transient_{i}_size, &transient_cursor)) {{",
            "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_CONFIG);",
            "    }",
        ])
    lines.append(f"    plan->transient_count = {len(transient_buffers)};")
    lines.append("    plan->transient_byte_length = transient_cursor;")

    for tensor, transient_index in graph_indices.items():
        transient_indices[tensor] = transient_index
    emit_graph_transient_materialization(lines, graph_indices, route_constant)
    if graph_indices:
        lines.append(f"    plan->transient_count = {len(transient_buffers) + len(graph_indices)};")

    lines.append(f"    plan->dispatch_count = {len(steps)};")
    for i, step in enumerate(steps):
        lines.append("    {")
        emit_config_materialization(lines, step)
        _, definition = step_definitions[i]
        emit_step_materialization(lines, route_id, steps, i, step, definition, context, transient_indices)
        lines.append("    }")

    lines.append(f"    return ggml_backend_hrx_loom_supported({route_constant});")


def fusion_op_var(op_name):
    return f"{c_identifier(op_name)}_op"


def fusion_role_expr(op_var, role):
    if role == "dst":
        return op_var
    if role.startswith("src") and role[3:].isdigit():
        return f"{op_var}->src[{int(role[3:])}]"
    raise ValueError(f"unsupported tensor role {role}")


def emit_fusion_tensor_role_assignments(lines, op_var, op_tensors):
    for role, tensor_name in op_tensors.items():
        expr = fusion_role_expr(op_var, role)
        tensor_var = route_emit.role_var(tensor_name)
        lines.extend([
            f"        if ({tensor_var} && {tensor_var} != {expr}) {{",
            "            return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_SHAPE);",
            "        }",
            f"        {tensor_var} = {expr};",
        ])


def emit_fusion_op_setup(lines, route, route_constant):
    match = route_schema.require_dict(route, "match", "route")
    ops = route_schema.require_dict(match, "ops", "route")
    op_names = list(ops)
    matched_node_count = len(op_names)
    reorder_enabled = match.get("reorder", False)
    lines.extend([
        f"    static constexpr int matched_node_count = {matched_node_count};",
        "    const bool reorder_match = ggml_backend_hrx_loom_reorder_match(request, plan);",
        f"    if (reorder_match && {'false' if reorder_enabled else 'true'}) {{",
        "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE);",
        "    }",
        "    if (!request->cgraph || request->node_index < 0 || request->node_index >= request->cgraph->n_nodes ||",
        "            request->cgraph->nodes[request->node_index] != node) {",
            "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE);",
            "    }",
        "    int matched_node_indices[matched_node_count] = {};",
        "    for (int i = 0; i < matched_node_count; ++i) {",
        "        matched_node_indices[i] = -1;",
        "    }",
    ])
    for op_name in op_names:
        lines.append(f"    const ggml_tensor * {fusion_op_var(op_name)} = nullptr;")
    for tensor_name in sorted(route_schema.route_tensors(route, "route")):
        lines.append(f"    const ggml_tensor * {route_emit.role_var(tensor_name)} = nullptr;")

    first_op_name = op_names[0]
    first_op = route_schema.require_string(ops[first_op_name], "op", "route")
    first_op_var = fusion_op_var(first_op_name)
    lines.extend([
        f"    {first_op_var} = node;",
        f"    if (!{first_op_var} || {first_op_var}->op != {first_op}) {{",
        "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE);",
        "    }",
        "    matched_node_indices[0] = request->node_index;",
        "    {",
    ])
    emit_fusion_tensor_role_assignments(
        lines,
        first_op_var,
        route_schema.require_dict(ops[first_op_name], "tensors", "route"),
    )
    lines.append("    }")

    for i, op_name in enumerate(op_names[1:], 1):
        op_tensors = route_schema.require_dict(ops[op_name], "tensors", "route")
        op = route_schema.require_string(ops[op_name], "op", "route")
        op_var = fusion_op_var(op_name)
        lines.extend([
            "    if (reorder_match) {",
            "        for (int candidate_index = request->node_index + 1; candidate_index < request->cgraph->n_nodes; ++candidate_index) {",
            "            if (ggml_backend_hrx_loom_node_index_is_matched(matched_node_indices, matched_node_count, candidate_index)) {",
            "                continue;",
            "            }",
            "            const ggml_tensor * candidate = request->cgraph->nodes[candidate_index];",
            f"            if (!candidate || candidate->op != {op}) {{",
            "                continue;",
            "            }",
            "            bool candidate_ok = true;",
        ])
        for role, tensor_name in op_tensors.items():
            expr = fusion_role_expr("candidate", role)
            tensor_var = route_emit.role_var(tensor_name)
            lines.extend([
                f"            if ({tensor_var} && {tensor_var} != {expr}) {{",
                "                candidate_ok = false;",
                "            }",
            ])
        lines.extend([
            "            if (!candidate_ok) {",
            "                continue;",
            "            }",
            f"            {op_var} = candidate;",
            f"            matched_node_indices[{i}] = candidate_index;",
            "            break;",
            "        }",
            "    } else {",
            f"        if (request->node_index + {i} >= request->cgraph->n_nodes) {{",
            "            return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE);",
            "        }",
            f"        {op_var} = request->cgraph->nodes[request->node_index + {i}];",
            f"        if (!{op_var} || {op_var}->op != {op}) {{",
            "            return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE);",
            "        }",
            f"        matched_node_indices[{i}] = request->node_index + {i};",
            "    }",
            f"    if (!{op_var}) {{",
            "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE);",
            "    }",
            "    {",
        ])
        emit_fusion_tensor_role_assignments(lines, op_var, op_tensors)
        lines.append("    }")

    tensors = route_schema.route_tensors(route, "route")
    required = sorted(name for name, tensor in tensors.items() if not tensor.get("optional", False))
    if required:
        condition = " || ".join([f"!{route_emit.role_var(name)}" for name in required])
        lines.extend([
            f"    if ({condition}) {{",
            "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_SHAPE);",
            "    }",
        ])


def emit_fusion_attributes(lines, route):
    match = route_schema.require_dict(route, "match", "route")
    ops = route_schema.require_dict(match, "ops", "route")
    for op_name, op_match in ops.items():
        op = route_schema.require_string(op_match, "op", "route")
        attributes = op_match.get("attributes", {})
        if not attributes:
            continue
        indices = ATTRIBUTE_INDICES[op]
        op_var = fusion_op_var(op_name)
        for name, attr in attributes.items():
            scalar_type = route_schema.require_string(attr, "type", "route")
            getter = route_emit.ATTRIBUTE_GETTERS[scalar_type]
            cast = CPP_SCALAR_TYPES[scalar_type]
            lines.append(f"    const {cast} {route_emit.fusion_attribute_var(op_name, name)} = {getter}({op_var}, {indices[name]});")


def generate_fusion_route_impl(route_path, route, definition):
    match = route_schema.require_dict(route, "match", route_path)
    ops = route_schema.require_dict(match, "ops", route_path)
    anchors = match.get("anchors", [])
    anchor_name = anchors[0] if anchors else next(iter(ops))
    anchor_op = route_schema.require_string(ops[anchor_name], "op", route_path)
    route_id = route_schema.require_string(route, "id", route_path)
    function_name = route_function_name(route_id)
    route_constant = route_id_constant(route_id)
    dispatches = route_schema.require_list(route, "dispatches", route_path)
    has_multiple_dispatches = len(dispatches) > 1
    context = route_schema.FusionRouteContext(
        route_path,
        route_schema.route_tensors(route, route_path),
        {op_name: op_match.get("attributes", {}) for op_name, op_match in ops.items()},
        route_schema.require_dict(route, "derived", route_path),
    )

    lines = []
    if has_multiple_dispatches:
        lines.append(MULTI_STEP_ROUTE_FUNCTION_OPEN_TEMPLATE.format(
            function_name=function_name,
            op=anchor_op,
        ))
    else:
        lines.append(ROUTE_FUNCTION_OPEN_TEMPLATE.format(
            function_name=function_name,
            op=anchor_op,
            route_id_constant=route_constant,
        ))
    emit_fusion_op_setup(lines, route, route_constant)
    route_emit.emit_dtype_checks(
        lines,
        route,
        route_schema,
        route_response,
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_DTYPE",
    )
    emit_fusion_attributes(lines, route)
    route_emit.emit_shape_captures(lines, route, route_schema)
    route_emit.emit_tensor_declaration_checks(
        lines,
        route,
        route_schema,
        route_response,
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_SHAPE",
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_LAYOUT",
    )
    route_emit.emit_derived(lines, route, context, route_schema, "ggml_backend_hrx_loom_next_power_of_2")
    route_emit.emit_predicates(lines, route, context, route_schema, UNSUPPORTED_REASON_BY_PREDICATE, route_response)
    if has_multiple_dispatches:
        emit_multi_step_plan_materialization(
            lines,
            route,
            definition,
            context,
            [f"matched_node_indices[{i}]" for i in range(len(ops))],
        )
    else:
        emit_plan_materialization(
            lines,
            route,
            definition,
            context,
            [f"matched_node_indices[{i}]" for i in range(len(ops))],
        )
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def generate_route_impl(route_path, route, definition):
    route_emit.validate_attribute_indices(route, route_path, route_schema, ATTRIBUTE_INDICES)
    if route_schema.route_is_fusion_v2(route, route_path):
        return generate_fusion_route_impl(route_path, route, definition)

    match = route_schema.require_dict(route, "match", route_path)
    op = route_schema.require_string(match, "op", f"{route_path}: match")
    op_rule = route_schema.OP_RULES[op]
    route_id = route_schema.require_string(route, "id", route_path)
    function_name = route_function_name(route_id)
    route_constant = route_id_constant(route_id)
    dispatches = route_schema.require_list(route, "dispatches", route_path)
    has_multiple_dispatches = len(dispatches) > 1
    context = route_schema.RouteContext(
        route_path,
        op_rule,
        route_schema.route_tensors(route, route_path),
        match.get("attributes", {}),
        route_schema.require_dict(route, "derived", route_path),
    )

    lines = []
    if has_multiple_dispatches:
        lines.append(MULTI_STEP_ROUTE_FUNCTION_OPEN_TEMPLATE.format(
            function_name=function_name,
            op=op,
        ))
    else:
        lines.append(ROUTE_FUNCTION_OPEN_TEMPLATE.format(
            function_name=function_name,
            op=op,
            route_id_constant=route_constant,
        ))
    lines.extend([
        "    if (ggml_backend_hrx_loom_reorder_match(request, plan)) {",
        "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE);",
        "    }",
    ])
    route_emit.emit_tensor_setup(
        lines,
        route,
        op_rule,
        route_schema,
        route_response,
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_SHAPE",
    )
    route_emit.emit_dtype_checks(
        lines,
        route,
        route_schema,
        route_response,
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_DTYPE",
    )
    route_emit.emit_attributes(lines, route, route_schema, ATTRIBUTE_INDICES)
    route_emit.emit_shape_captures(lines, route, route_schema)
    route_emit.emit_tensor_declaration_checks(
        lines,
        route,
        route_schema,
        route_response,
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_SHAPE",
        "GGML_BACKEND_HRX_LOOM_UNSUPPORTED_LAYOUT",
    )
    route_emit.emit_derived(lines, route, context, route_schema, "ggml_backend_hrx_loom_next_power_of_2")
    route_emit.emit_predicates(lines, route, context, route_schema, UNSUPPORTED_REASON_BY_PREDICATE, route_response)
    if has_multiple_dispatches:
        emit_multi_step_plan_materialization(lines, route, definition, context)
    else:
        emit_plan_materialization(lines, route, definition, context)
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def generate_dispatcher_impl(routes):
    lines = [DISPATCHER_CPP_HEADER_TEMPLATE]
    route_infos = route_emit.route_infos_for_dispatcher(routes, route_schema)
    ops = route_emit.ops_from_route_infos(route_infos)

    for op in ops:
        lines.extend([
            f"ggml_backend_hrx_loom_op_response {op_router_function_name(op)}(",
            "        ggml_backend_hrx_loom_catalog * catalog,",
            "        const ggml_backend_hrx_loom_op_request * request,",
            "        ggml_backend_hrx_loom_execution_plan * plan);",
            "",
        ])

    lines.append(DISPATCHER_FUNCTION_OPEN_TEMPLATE)
    for op in ops:
        lines.extend([
            f"        case {op}:",
            f"            return {op_router_function_name(op)}(catalog, request, plan);",
        ])
    lines.append(DISPATCHER_FUNCTION_CLOSE_TEMPLATE)
    lines.append(REORDER_DISPATCHER_FUNCTION_OPEN_TEMPLATE)
    for op in ops:
        lines.extend([
            f"        case {op}:",
            f"            return {op_router_function_name(op)}(catalog, request, plan);",
        ])
    lines.append(DISPATCHER_FUNCTION_CLOSE_TEMPLATE)
    return "\n".join(lines)


def generate_op_router_impl(routes, selected_op):
    lines = [DISPATCHER_CPP_HEADER_TEMPLATE]

    route_infos = route_emit.route_infos_for_op(routes, selected_op, route_schema)
    if not route_infos:
        raise ValueError(f"no routes found for {selected_op}")

    for _, _, route_path, route, definition in route_infos:
        route_id = route_schema.require_string(route, "id", route_path)
        lines.extend([
            f"static constexpr const char * {route_id_constant(route_id)} = {cpp_string(route_id)};",
            "",
        ])
        dispatches = route_schema.require_list(route, "dispatches", route_path)
        if len(dispatches) > 1:
            for step in dispatches:
                step_name = route_schema.require_string(step, "name", route_path)
                step_entry_id = f"{route_id}::{step_name}"
                lines.extend([
                    f"static constexpr const char * {step_entry_constant(route_id, step_name)} = {cpp_string(step_entry_id)};",
                    "",
                ])
        lines.append(generate_route_impl(route_path, route, definition))

    function_name = op_router_function_name(selected_op)
    lines.extend([
        f"ggml_backend_hrx_loom_op_response {function_name}(",
        "        ggml_backend_hrx_loom_catalog * catalog,",
        "        const ggml_backend_hrx_loom_op_request * request,",
        "        ggml_backend_hrx_loom_execution_plan * plan);",
        "",
        f"ggml_backend_hrx_loom_op_response {function_name}(",
        "        ggml_backend_hrx_loom_catalog * catalog,",
        "        const ggml_backend_hrx_loom_op_request * request,",
        "        ggml_backend_hrx_loom_execution_plan * plan) {",
        "    ggml_backend_hrx_loom_op_response fallback =",
        "        ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE);",
        '    const char * forced_route = std::getenv("GGML_HRX_LOOM_FORCE_ROUTE");',
        "",
    ])

    for _, route_id, _, _, _ in route_infos:
        route_constant = route_id_constant(route_id)
        lines.extend([
            "    {",
            f"        if (!forced_route || std::strcmp(forced_route, {route_constant}) == 0) {{",
            "            ggml_backend_hrx_loom_op_response response =",
            f"                {route_function_name(route_id)}(catalog, request, plan);",
            "            if (response.result != GGML_BACKEND_HRX_LOOM_UNSUPPORTED) {",
            "                return response;",
            "            }",
            "            if (fallback.unsupported_reason == GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE &&",
            "                response.unsupported_reason != GGML_BACKEND_HRX_LOOM_UNSUPPORTED_NO_ROUTE) {",
            "                fallback = response;",
            "            }",
            "        }",
            "    }",
            "",
        ])

    lines.extend([
        "    return fallback;",
        "}",
        "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-root", default=str(route_validator.default_source_root()))
    parser.add_argument("--route", required=True, action="append")
    parser.add_argument("--out", required=True)
    parser.add_argument("--dispatcher", action="store_true")
    parser.add_argument("--op-router", action="store_true")
    parser.add_argument("--op")
    args = parser.parse_args()

    try:
        routes = [load_route(Path(args.source_root), route_name) for route_name in args.route]
        if args.dispatcher:
            output = generate_dispatcher_impl([(route_path, route, definition) for route_path, route, _, definition in routes])
        elif args.op_router:
            if not args.op:
                raise ValueError("--op-router expects --op")
            output = generate_op_router_impl([(route_path, route, definition) for route_path, route, _, definition in routes], args.op)
        else:
            raise ValueError("expected --dispatcher or --op-router")
        out_path = Path(args.out)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(output, encoding="utf-8")
    except (OSError, json.JSONDecodeError, ValueError) as err:
        print(f"ValueError: {err}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
