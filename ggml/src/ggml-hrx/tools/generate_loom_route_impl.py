def config_value_expr(binding):
    scalar_type = route_schema.require_string(binding, "type", "route")
    if "source" in binding:
        return typed_expr(source_expr(route_schema.require_string(binding, "source", "route")), scalar_type)
    return scalar_literal(binding["value"], scalar_type)


def config_format_args(value_var, scalar_type):
    if scalar_type in {"i32", "i64", "index"}:
        return '"%lld"', f"static_cast<long long>({value_var})"
    if scalar_type == "f32":
        return '"%.9g"', f"static_cast<double>({value_var})"
    if scalar_type == "f64":
        return '"%.17g"', value_var
    raise ValueError(f"unsupported config type {scalar_type}")


def config_value_var(binding):
    return f"config_{c_identifier(route_schema.require_string(binding, 'name', 'route'))}_value"


def config_text_var(binding):
    return f"config_{c_identifier(route_schema.require_string(binding, 'name', 'route'))}_text"


def config_length_var(binding):
    return f"config_{c_identifier(route_schema.require_string(binding, 'name', 'route'))}_length"


def emit_config_materialization(lines, route_dispatch):
    config = route_schema.require_dict(route_dispatch, "config", "route")
    bindings = route_schema.require_array(config, "bindings", "route")
    for binding in bindings:
        scalar_type = route_schema.require_string(binding, "type", "route")
        cpp_type = CPP_SCALAR_TYPES[scalar_type]
        value_var = config_value_var(binding)
        text_var = config_text_var(binding)
        length_var = config_length_var(binding)
        format_text, format_value = config_format_args(value_var, scalar_type)
        lines.extend([
            f"    const {cpp_type} {value_var} = {config_value_expr(binding)};",
            f"    char {text_var}[128] = {{}};",
            f"    const int {length_var} = std::snprintf({text_var}, sizeof({text_var}), {format_text}, {format_value});",
            f"    if ({length_var} < 0 || static_cast<size_t>({length_var}) >= sizeof({text_var})) {{",
            "        return ggml_backend_hrx_loom_unsupported(GGML_BACKEND_HRX_LOOM_UNSUPPORTED_CONFIG);",
            "    }",
        ])


def emit_dispatch_config_plan_copy(lines, route_dispatch, dispatch_expr):
    config = route_schema.require_dict(route_dispatch, "config", "route")
    bindings = route_schema.require_array(config, "bindings", "route")
    for i, binding in enumerate(bindings):
        name = route_schema.require_string(binding, "name", "route")
        scalar_type = route_schema.require_string(binding, "type", "route")
        text_var = config_text_var(binding)
        lines.extend([
            f"    std::memcpy({dispatch_expr}.config_bindings[{i}].name, {cpp_string(name)}, sizeof({cpp_string(name)}));",
            f"    std::memcpy({dispatch_expr}.config_bindings[{i}].value, {text_var}, static_cast<size_t>({config_length_var(binding)}) + 1);",
            f"    {dispatch_expr}.config_bindings[{i}].type = {cpp_string(scalar_type)};",
        ])
    lines.append(f"    {dispatch_expr}.config_binding_count = {len(bindings)};")


def emit_step_config_plan_copy(lines, step, step_expr):
    emit_dispatch_config_plan_copy(lines, step, step_expr)


